// Equal-leg hot-rolled L-angles (UNE-EN 10056-1 / EN 10056-1)
//
// PROCEDENCIA (revisado 2026-09-25): geometría EXACTA de la sección —dos rectángulos,
// más el acuerdo interior r1, menos los dos redondeos r2 de las puntas— con los radios
// que tabula la EN 10056-1 para cada lado (r1/r2: 60→8/4, 70·75→9/4,5, 80→10/5,
// 90→11/5,5, 100·110→12/6, 120→13/6,5, 130→14/7, 140→15/7,5, 150→16/8, 160→17/8,5).
// Cotejado contra 21 filas de la propia EN 10056-1: desviación máxima 0,62 % (A, I,
// iv y e). Hasta esa fecha los valores estaban calculados SIN acuerdos: la inercia
// salía hasta un 3,1 % alta, el centro de gravedad hasta un 2,5 % alto y el radio de
// giro mínimo iv —el que manda en el pandeo del cordón entre presillas— hasta un
// 1,6 % alto, del lado inseguro. Generador: scratchpad gen_angles.py (misma fórmula
// que el test angleProfiles.test.ts, que fija las 21 filas de catálogo al 0,7 %).
//
// Unit convention:
//   b, t   → mm   (leg width, thickness)
//   A      → cm²  (cross-sectional area)
//   I1     → cm⁴  (moment of inertia about centroidal axis parallel to leg = (Iu + Iv)/2)
//   iv     → cm   (radius of gyration about minor principal axis v)
//   e      → cm   (centroid distance from back of leg)

